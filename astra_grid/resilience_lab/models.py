@dataclass
class DiagnosticAnnotation:
    """Evidence-based rule annotation for operator awareness and auditability."""
    step: int
    rule_id: str
    severity: Literal["INFO", "WARNING", "CRITICAL"]
    explanation: str
    category: Literal["OBSERVATION", "INFERENCE"]
    observed_evidence: dict[str, Any] = field(default_factory=dict)
    supporting_references: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class ReplayStep:
    """Complete 8-part replay breakdown for a single simulation timestep."""
    step: int
    observation: dict[str, Any]
    estimated_state: dict[str, Any]
    estimated_capability: dict[str, Any]
    proposed_plan: dict[str, Any] | None
    validation_result: dict[str, Any] | None
    accepted_plan: dict[str, Any] | None
    executed_action: dict[str, Any] | None
    physical_transition: dict[str, Any] | None
    physical_state_after: dict[str, Any] | None
    shortfalls_and_warnings: dict[str, Any]
    events: list[dict[str, Any]] = field(default_factory=list)
    annotations: list[dict[str, Any]] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class RunRecord:
    """Complete record of an evaluated simulation run."""
    run_id: str
    scenario_id: str
    controller: str
    seed: int | None
    repetition: int
    duration_steps: int
    simulated_steps: int
    simulated_hours: float
    completed: bool
    stop_reason: str
    wall_runtime_s: float | None = None
    execution_error: str | None = None
    metrics: dict[str, Any] = field(default_factory=dict)
    fault_detection_delays: dict[str, int] = field(default_factory=dict)
    task_completion_timeline: list[dict[str, Any]] = field(default_factory=list)
    diagnostic_annotations: list[DiagnosticAnnotation] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["diagnostic_annotations"] = [a.to_dict() if hasattr(a, "to_dict") else a for a in self.diagnostic_annotations]
        return data


@dataclass
class ExperimentConfig:
    """Specification for an automated experiment run."""
    name: str = "resilience_lab_experiment"
    description: str = "AstraGrid Resilience Lab systematic evaluation experiment"
    scenario_ids: list[str] = field(default_factory=lambda: [
        "nominal_day",
        "solar_array_damage",
        "battery_degradation_or_failure",
        "byzantine_soc_sensor",
        "combined_fault",
        "hard_deadline_under_shortage",
        "constrained_task_selection",
        "deadline_release_pressure",
    ])
    seeds: list[int] = field(default_factory=lambda: [42])
    controllers: list[str] = field(default_factory=lambda: ["astragrid", "baseline"])
    repetitions: int = 1
    steps: int | None = None
    output_dir: Path = field(default_factory=lambda: Path("outputs") / "resilience_lab")
    save_detailed_history: bool = True
    fault_variations: list[dict[str, Any]] | None = None

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["output_dir"] = str(self.output_dir)
        return data


